#!/usr/bin/env python3
"""Bake model + witness bytes into C sources for the scandor link.

Reads a trained model file and keyed witness rows, hash-checks both against
the pinned proven values, and emits generated sources. Nothing is transformed:
the bytes linked are the bytes measured.

usage: bake.py --model F --witness F --out-dir D
                --expect-model-sha256 H --expect-witness-sha256 H
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--witness", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--expect-model-sha256", required=True)
    ap.add_argument("--expect-witness-sha256", required=True)
    a = ap.parse_args()
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    raw = Path(a.model).read_bytes()
    mh = hashlib.sha256(raw).hexdigest()
    if mh != a.expect_model_sha256:
        sys.exit(f"bake: model hash mismatch:\n  got    {mh}\n  pinned {a.expect_model_sha256}\n"
                 f"refusing to bake an unproven model.")
    rows = []
    for line in Path(a.witness).read_text().splitlines():
        if not line.strip():
            continue
        d = json.loads(line)
        if "entity" in d and "fact" in d:
            rows.append(line)
    text = "\n".join(rows) + "\n"
    wh = hashlib.sha256(text.encode()).hexdigest()
    if wh != a.expect_witness_sha256:
        sys.exit(f"bake: witness hash mismatch:\n  got    {wh}\n  pinned {a.expect_witness_sha256}\n"
                 f"refusing to bake unproven memory.")
    print(f"  model: {len(raw)} bytes sha256={mh[:16]}... OK (pinned)")
    print(f"  witness: {len(rows)} rows sha256={wh[:16]}... OK (pinned)")

    (out / "model_blob.c").write_text(
        "/* GENERATED by tools/bake.py -- do not edit. Exact bytes of the shipped model. */\n"
        "#include <stddef.h>\n"
        "const unsigned char CANDOR_MODEL[] = {\n" +
        ",".join(f"0x{b:02x}" + ("\n" if (i + 1) % 12 == 0 else "") for i, b in enumerate(raw)) +
        "\n};\nconst unsigned CANDOR_MODEL_LEN = sizeof CANDOR_MODEL;\n")
    esc = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n\"\n\"")
    (out / "witness_blob.c").write_text(
        "/* GENERATED by tools/bake.py -- do not edit. Exact witness bytes. */\n"
        f'const char CANDOR_WITNESS[] = "{esc}";\n')
    about = (f"baked scandor model_sha256={mh} witness_rows={len(rows)} "
             f"witness_sha256={wh} container=v3/q8 spec=candor-r1")
    (out / "about.h").write_text(f'/* GENERATED by tools/bake.py. */\n#define CANDOR_ABOUT "{about}"\n')
    (out / "about.txt").write_text(about + "\n")
    print("  baked.")


if __name__ == "__main__":
    sys.exit(main())
